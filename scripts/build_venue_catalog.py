"""Validate researched venue data and render the bundled Flutter catalog."""
import argparse
import json
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [ROOT / "docs/research/venues_seoul.json", ROOT / "docs/research/venues_regions.json"]
REQUIRED = {"id", "name", "address", "kind", "capacity", "capacityNote", "equipment", "hours",
            "description", "fitReason", "verificationNeeded", "sourceUrl", "sourceTitle", "checkedAt"}


def render():
    venues = [venue for source in SOURCES for venue in json.loads(source.read_text())]
    assert len(venues) == 40, f"Expected 40 venues, got {len(venues)}"
    assert len({v["id"] for v in venues}) == 40, "Duplicate IDs"
    assert len({v["name"].replace(" ", "").casefold() for v in venues}) == 40, "Duplicate names"
    for venue in venues:
        assert REQUIRED <= venue.keys(), f"Missing fields: {venue.get('name')}"
        assert venue["kind"] in {"cafe", "studio", "bookstore", "gallery", "culture", "hall"}
        assert venue["capacity"] is None or (type(venue["capacity"]) is int and venue["capacity"] > 0)
        assert urlparse(venue["sourceUrl"]).scheme == "https" and urlparse(venue["sourceUrl"]).netloc
        assert all(isinstance(venue[k], str) and venue[k].strip() for k in REQUIRED - {"capacity"})
    dart = "// Generated by scripts/build_venue_catalog.py from researched source records.\n"
    dart += "const venueCandidates = <Map<String, dynamic>>"
    dart += json.dumps(venues, ensure_ascii=False, indent=2).replace("$", r"\$") + ";\n"
    lines = [
        "# CrocTick 실제 공간 후보 40곳",
        "",
        "확인일: 2026-11-11. 공개 운영 안내·호스트 등록을 확인한 제휴 문의 후보이며, 제휴나 예약이 확정된 공간 목록이 아닙니다.",
        "",
        "## 선정 기준",
        "",
        "- 독립 관람 구역과 출입 관리가 가능한 실내 공간을 우선합니다.",
        "- 20~50명 규모의 어쿠스틱·소규모 음악회와 단독 사용 근거를 우선합니다.",
        "- 규모가 더 크거나 공연 허용을 확인하지 못한 후보는 개별 조건과 보완점을 표시합니다.",
        "- 유료 입장, 허용 음량, 안전·대피, 현재 영업·예약 가능 여부, 티켓 매출 50% 배분은 운영자 확인이 필요합니다.",
        "- 정원 미공개 후보의 앱 내 30명은 시연 입력값입니다. 확인된 실제 정원으로 표시하지 않습니다.",
        "",
        "## 앱에 반영한 내용",
        "",
        "후보 40곳과 가상 공연 40개를 추가합니다. 기존 시연 공간·공연 4개씩은 보존하므로 새 설치 기준 각 44개이며, 사용자 등록·티켓·Tick 내역도 보존합니다.",
        "추가 공연의 출연자·일정·티켓가·펀딩 금액은 전부 시연 값입니다. 실제 공연 예정이나 장소 대관 승인으로 해석하면 안 됩니다.",
        "확보되지 않은 장소 사진은 사진 준비 중으로 표시하고 다른 공간 사진을 대신 사용하지 않습니다.",
        "",
        "## 후보 목록",
        "",
        "| 번호 | 실제 공간 | 위치 | 공개 최대 인원 | 출처 |",
        "|---|---|---|---|---|",
    ]
    for i, v in enumerate(venues, 1):
        capacity = f'{v["capacity"]}명' if v["capacity"] is not None else "미확인"
        lines.append(f'| {i} | {v["name"]} | {v["address"]} | {capacity} | [운영자·등록 원문]({v["sourceUrl"]}) |')
    for i, v in enumerate(venues, 1):
        lines += [
            "", f'## {i}. {v["name"]}', "",
            f'- 공개 정보: {v["description"]}',
            f'- 선정 이유: {v["fitReason"]}',
            f'- 정원 해석: {v["capacityNote"]}',
            f'- 장비: {v["equipment"]}',
            f'- 시간: {v["hours"]}',
            f'- 확인할 조건: {v["verificationNeeded"]}',
            f'- 출처: [{v["sourceTitle"]}]({v["sourceUrl"]})',
        ]
    lines += [
        "", "## 저장과 서버", "",
        "이번 변경은 오프라인 시연 카탈로그를 기기 저장소에 추가하므로 Railway DB를 생성하지 않았습니다.",
        "catalogVersion과 고정 ID로 한 번만 추가하며, 기존 티켓·펀딩·사용자 공간·공연·사진·Tick은 유지합니다.",
        "여러 계정·기기가 데이터를 함께 쓰는 운영 서비스로 전환할 때 Railway API와 PostgreSQL을 연결해야 합니다.",
        "",
    ]
    return {ROOT / "flutter_app/lib/venue_candidates.dart": dart,
            ROOT / "docs/REAL_VENUE_CATALOG.md": "\n".join(lines)}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        for path, content in generated.items():
            assert path.read_text() == content, f"Out of date: {path}"
        print("40 unique sourced candidates; generated catalog and report match.")
    else:
        print("*** Begin Patch")
        for path, content in generated.items():
            assert not path.exists(), f"Already exists: {path}; use --check for verification."
            print(f"*** Add File: {path}")
            print("\n".join("+" + line for line in content.splitlines()))
        print("*** End Patch")
